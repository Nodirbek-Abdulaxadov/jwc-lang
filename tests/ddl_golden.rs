/// Applies every golden to a real Postgres. Opt-in via `JWC_V1_PG`, which
/// is a psql connection string (`postgres://…` or `-h /path -p 5432 -U u`).
#[test]
fn goldens_apply_to_postgres() {
    let Ok(conn) = std::env::var("JWC_V1_PG") else {
        eprintln!(
            "SKIPPED goldens_apply_to_postgres — set JWC_V1_PG to a psql \
             connection string. A SKIPPED line is not a pass."
        );
        return;
    };

    let mut files: Vec<PathBuf> = cases().iter().map(|c| c.with_extension("sql")).collect();
    files.push(repo_root().join("tests/ddl_golden/sample.sql"));

    for (i, f) in files.iter().enumerate() {
        let db = format!("jwc_v1_golden_{i}");
        run_psql(
            &conn,
            "postgres",
            &["-c", &format!("DROP DATABASE IF EXISTS {db}")],
        );
        run_psql(&conn, "postgres", &["-c", &format!("CREATE DATABASE {db}")]);
        let out = run_psql(
            &conn,
            &db,
            &[
                "-q",
                "-v",
                "ON_ERROR_STOP=1",
                "-f",
                &f.display().to_string(),
            ],
        );
        assert!(
            out.trim().is_empty(),
            "{} did not apply cleanly:\n{out}",
            f.display()
        );
        run_psql(&conn, "postgres", &["-c", &format!("DROP DATABASE {db}")]);
    }
}
