/// The AOT path has to agree with the interpreter on `having`: aggregate
/// comparisons emit the aggregate, and a projection alias is resolved to the
/// aggregate it names (Postgres rejects an output alias in `HAVING`).
#[test]
fn emit_rust_source_lowers_having_aggregates_and_aliases() {
    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path();
    let program = parse(
        r#"
        dbcontext AppDb : Postgres;
        entity Sale of AppDb {
            id int pk;
            country varchar(64);
            amount int;
        }

        function busy() {
            return select Sale { country, total: count(*) } from AppDb.Sale
                group by Sale.country
                having count(*) > 2 and sum(Sale.amount) >= 500;
        }

        function viaAlias() {
            return select Sale { country, total: count(*) } from AppDb.Sale
                group by Sale.country
                having total > 2;
        }

        function main() { busy(); viaAlias(); }
    "#,
    );

    let out = emit_rust_source(&program, root, "having_app", false).expect("emit");
    let body = fs::read_to_string(&out).expect("read generated");

    assert!(
        body.contains("HAVING (COUNT(*) > $1 AND SUM("),
        "aggregate comparison must lower to the SQL aggregate; got:\n{}",
        having_lines(&body)
    );
    // The alias query names no aggregate of its own — if the alias were passed
    // through as a column the emitted SQL would say `\"total\"` here, which is
    // what fails at the database.
    assert!(
        !body.contains("HAVING \\\"total\\\""),
        "a projection alias must not reach SQL as a column; got:\n{}",
        having_lines(&body)
    );
    assert!(
        body.matches("HAVING COUNT(*) > $1").count() >= 1,
        "the alias query must lower to COUNT(*); got:\n{}",
        having_lines(&body)
    );
}

fn having_lines(body: &str) -> String {
    body.lines()
        .filter(|l| l.contains("HAVING"))
        .collect::<Vec<_>>()
        .join("\n")
}

/// `distinct` has to reach the AOT SQL too — the interpreter and the compiled
/// binary must not disagree on how many rows a query returns.
#[test]
fn emit_rust_source_lowers_select_distinct() {
    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path();
    let program = parse(
        r#"
        dbcontext AppDb : Postgres;
        entity Sale of AppDb {
            id int pk;
            country varchar(64);
        }

        function countries() {
            return select distinct Sale { country } from AppDb.Sale;
        }

        function all() {
            return select Sale { country } from AppDb.Sale;
        }

        function main() { countries(); all(); }
    "#,
    );

    let out = emit_rust_source(&program, root, "distinct_app", false).expect("emit");
    let body = fs::read_to_string(&out).expect("read generated");

    assert!(
        body.contains("SELECT DISTINCT \\\"country\\\" FROM \\\"sale\\\""),
        "`select distinct` must lower to SELECT DISTINCT; got:\n{}",
        select_lines(&body)
    );
    assert!(
        body.contains("SELECT \\\"country\\\" FROM \\\"sale\\\""),
        "the non-distinct query must stay non-distinct; got:\n{}",
        select_lines(&body)
    );
}

fn select_lines(body: &str) -> String {
    body.lines()
        .filter(|l| l.contains("FROM \\\"sale\\\""))
        .collect::<Vec<_>>()
        .join("\n")
}

/// Guard on the `is_async_builtin` list in `native_build.rs`.
///
/// Every `file.*` / `directory.*` / `console.read` builtin is an `async fn`
/// in the prelude, so codegen must emit `.await` on the call. Missing an
/// entry in that `matches!` produces a `Future`-vs-`V` type error inside
/// the *generated* crate, which only surfaces on a real `jwc build
/// --native` — neither the conformance suite nor `native_parity` compiles
/// emitted source. This test is the cheap version of that check.
///
/// `console.write` / `console.error` are deliberately synchronous, so they
/// must NOT get `.await`; that direction is asserted too, because adding
/// them to the async list would break the build just as thoroughly.
#[test]
fn emit_rust_source_awaits_async_io_builtins() {
    let tmp = tempfile::tempdir().expect("tempdir");
    let root = tmp.path();
    let src = r#"
        function main() {
            console.write("a");
            console.error("b");
            let line = console.read();
            directory.create("d");
            let t = file.read("d/x.txt");
            file.write("d/x.txt", "y");
            file.append("d/x.txt", "z");
            let ex = file.exists("d/x.txt");
            let sz = file.size("d/x.txt");
            let ls = file.lines("d/x.txt");
            file.copy("d/x.txt", "d/y.txt");
            file.move("d/y.txt", "d/z.txt");
            file.delete("d/z.txt");
            let names = directory.list("d");
            let de = directory.exists("d");
            directory.delete("d");
            // RS256 verification fetches the issuer's JWKS, so it suspends.
            let claims = jwt_verify_jwks("tok", "https://idp.test/jwks");
        }
    "#;
    let program = parse(src);
    let out = emit_rust_source(&program, root, "iotest", false).expect("emit");
    let body = fs::read_to_string(&out).expect("read generated");

    for name in [
        "jwc_b_jwt_verify_jwks",
        "jwc_b_console_read",
        "jwc_b_file_read",
        "jwc_b_file_write",
        "jwc_b_file_append",
        "jwc_b_file_exists",
        "jwc_b_file_delete",
        "jwc_b_file_copy",
        "jwc_b_file_move",
        "jwc_b_file_size",
        "jwc_b_file_lines",
        "jwc_b_directory_list",
        "jwc_b_directory_create",
        "jwc_b_directory_exists",
        "jwc_b_directory_delete",
    ] {
        // The call site inside `user_main`, not the `async fn` definition
        // the prelude contributes — hence the `(` and the `.await` check on
        // the same emitted line.
        let called = body
            .lines()
            .filter(|l| l.contains(&format!("{name}(")) && !l.contains(&format!("fn {name}")))
            .collect::<Vec<_>>();
        assert!(!called.is_empty(), "{name} was never called in the output");
        for line in called {
            assert!(
                line.contains(".await"),
                "{name} emitted without `.await` — add it to `is_async_builtin` \
                 in native_build.rs. Line: {line}"
            );
        }
    }

    // Sync direction, checked on a separate program so each console call is
    // the only thing on its emitted line. In the program above the
    // arguments are literals, but a nested async call would put an unrelated
    // `.await` on the same line and make the assertion meaningless.
    let tmp2 = tempfile::tempdir().expect("tempdir");
    let sync_src = r#"
        function main() {
            console.write("a");
            console.error("b");
        }
    "#;
    let program2 = parse(sync_src);
    let out2 = emit_rust_source(&program2, tmp2.path(), "synctest", false).expect("emit");
    let body2 = fs::read_to_string(&out2).expect("read generated");

    for name in ["jwc_b_console_write", "jwc_b_console_error"] {
        let called = body2
            .lines()
            .filter(|l| l.contains(&format!("{name}(")) && !l.contains(&format!("fn {name}")))
            .collect::<Vec<_>>();
        assert!(!called.is_empty(), "{name} was never called in the output");
        for line in called {
            assert!(
                !line.contains(".await"),
                "{name} must not be awaited — it is synchronous, and adding it \
                 to `is_async_builtin` breaks the generated crate. Line: {line}"
            );
        }
    }
}

/// Same guard as above, for the Redis built-ins — plus a check that the
/// Redis prelude fragment actually gets concatenated.
///
/// The coverage assertion is the point: the exercised set is compared
/// against every `redis_*` row in `BUILTIN_DEFS`, so adding a tenth Redis
/// built-in without teaching `is_async_builtin` about it fails here rather
/// than in a user's `jwc build --native`.
#[test]
fn emit_rust_source_awaits_redis_builtins() {
    let tmp = tempfile::tempdir().expect("tempdir");
    let src = r#"
        function main() {
            let on = redis_enabled();
            let up = redis_ping();
            let v = redis_get("k");
            redis_set("k", "v", 60);
            let n = redis_del("k");
            let has = redis_exists("k");
            let c = redis_incr("hits");
            let ok = redis_expire("hits", 60);
            let r = redis_eval("return 1", "[]", "[]");
        }
    "#;
    let program = parse(src);
    let out = emit_rust_source(&program, tmp.path(), "redistest", false).expect("emit");
    let body = fs::read_to_string(&out).expect("read generated");

    // The prelude fragment must be present, or every call below resolves
    // to nothing and the generated crate fails on unknown functions.
    assert!(
        body.contains("fn jwc_redis_pool()"),
        "native_prelude_redis.rs.in was not concatenated — check \
         `program_uses_redis` / REDIS_BUILTINS in native_build.rs"
    );

    let exercised: Vec<&str> = jwc::builtins::BUILTIN_DEFS
        .iter()
        .map(|d| d.name)
        .filter(|n| n.starts_with("redis_"))
        .collect();
    assert_eq!(
        exercised.len(),
        9,
        "the Redis built-in set changed; add the new call to this test's \
         program so its `.await` is covered: {exercised:?}"
    );

    for name in exercised {
        let emitted = format!("jwc_b_{name}");
        let called = body
            .lines()
            .filter(|l| l.contains(&format!("{emitted}(")) && !l.contains(&format!("fn {emitted}")))
            .collect::<Vec<_>>();
        assert!(
            !called.is_empty(),
            "{emitted} was never called in the output"
        );
        for line in called {
            assert!(
                line.contains(".await"),
                "{emitted} emitted without `.await` — add it to \
                 `is_async_builtin` in native_build.rs. Line: {line}"
            );
        }
    }
}

