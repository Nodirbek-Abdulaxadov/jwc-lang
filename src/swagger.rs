#[cfg(test)]
mod tests {
    use super::*;
    use crate::parser::{parse_program, validate_program};

    fn build(src: &str) -> Value {
        let p = parse_program(src).expect("parse");
        validate_program(&p).expect("validate");
        generate_openapi(&p, "test", "0.0.0")
    }

    #[test]
    fn empty_program_has_openapi_skeleton() {
        let doc = build(r#"function main() { print("hi"); }"#);
        assert_eq!(doc["openapi"], "3.1.0");
        assert_eq!(doc["info"]["title"], "test");
        assert!(doc["paths"].as_object().unwrap().is_empty());
    }

    #[test]
    fn route_with_path_param_emits_parameter() {
        let doc = build(
            r#"
            function getUser(id: int) { return ok({ id: id }); }
            route GET "/users/{id}" -> getUser;
            function main() { print("ok"); }
        "#,
        );
        let op = &doc["paths"]["/users/{id}"]["get"];
        assert_eq!(op["operationId"], "getUser");
        let params = op["parameters"].as_array().unwrap();
        assert_eq!(params.len(), 1);
        assert_eq!(params[0]["name"], "id");
        assert_eq!(params[0]["in"], "path");
        assert_eq!(params[0]["schema"]["type"], "integer");
    }

    #[test]
    fn validate_body_block_lands_in_request_body() {
        let doc = build(
            r#"
            route POST "/users" {
                validate body {
                    name:  required, minLength(2), maxLength(64);
                    email: required, pattern("^[^@]+@[^@]+$");
                }
                let req = body();
                return created(req);
            }
            function main() { print("ok"); }
        "#,
        );
        let body =
            &doc["paths"]["/users"]["post"]["requestBody"]["content"]["application/json"]["schema"];
        let props = body["properties"].as_object().unwrap();
        assert!(props.contains_key("name"));
        assert!(props.contains_key("email"));
        let req: Vec<String> = body["required"]
            .as_array()
            .unwrap()
            .iter()
            .map(|v| v.as_str().unwrap().to_string())
            .collect();
        assert!(req.contains(&"name".to_string()));
        assert!(req.contains(&"email".to_string()));
        assert_eq!(props["name"]["minLength"], 2);
        assert_eq!(props["email"]["pattern"], "^[^@]+@[^@]+$");
    }

    #[test]
    fn class_becomes_component_schema() {
        let doc = build(
            r#"
            class UserView {
                id    string;
                name  string;
                age   int;
            }
            function main() { print("ok"); }
        "#,
        );
        let schema = &doc["components"]["schemas"]["UserView"];
        assert_eq!(schema["type"], "object");
        let props = schema["properties"].as_object().unwrap();
        assert_eq!(props["age"]["type"], "integer");
        let req: Vec<String> = schema["required"]
            .as_array()
            .unwrap()
            .iter()
            .map(|v| v.as_str().unwrap().to_string())
            .collect();
        assert!(req.contains(&"id".to_string()));
    }

    #[test]
    fn response_codes_picked_up_from_builders() {
        let doc = build(
            r#"
            route POST "/maybe" {
                if (true) { return created({ id: 1 }); }
                return badRequest({ error: "x" });
            }
            function main() { print("ok"); }
        "#,
        );
        let responses = doc["paths"]["/maybe"]["post"]["responses"]
            .as_object()
            .unwrap();
        assert!(responses.contains_key("201"));
        assert!(responses.contains_key("400"));
    }
}
